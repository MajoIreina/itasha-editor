const { _electron: electron } = require('../desktop/node_modules/playwright-core');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { PNG } = require('../desktop/node_modules/pngjs');
const root = path.resolve(__dirname, '..');
const output = path.join(__dirname, 'acceptance', 'electron-rust');
const data = fs.mkdtempSync(path.join(require('node:os').tmpdir(), 'itasha-electron-'));
fs.mkdirSync(output, { recursive: true });
fs.mkdirSync(path.join(data, 'projects'), { recursive: true });
fs.copyFileSync(path.join(root, 'projects', '示例-蓝曜流线.su7design'), path.join(data, 'projects', '示例-蓝曜流线.su7design'));
const checks = [], errors = [], measurements = {};
let application, page;
const check = (name, condition) => { assert.ok(condition, name); checks.push(name); console.log('PASS ' + name); };

(async () => {
  application = await electron.launch({ executablePath: path.join(root, 'desktop/electron/痛车编辑器.exe'), cwd: root, env: { ...process.env, ITASHA_ROOT: root, ITASHA_DATA_DIR: data, ITASHA_PROFILE_DIR: path.join(data, 'profile'), ITASHA_PORT: '0', ITASHA_TEST_MODE: '1' }, timeout: 60000 });
  page = await application.firstWindow();
  await application.evaluate(({BrowserWindow})=>{const w=BrowserWindow.getAllWindows()[0];w.setPosition(-30000,-30000,false);w.showInactive();});
  page.on('pageerror', e => errors.push(e.stack));
  page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
  page.on('dialog', d => d.accept().catch(() => {}));
  page.setDefaultTimeout(30000);
  await page.waitForFunction(() => window.studio && window.ItashaAPI);
  const info = await page.evaluate(async () => ({ host: itashaHost, node: typeof require, process: typeof process, health: await (await fetch('/__studio_health')).json() }));
  check('Packaged Electron connects to the Rust backend', info.host.host === 'electron' && info.health.backend === 'rust');
  check('Renderer is isolated from Node.js', info.node === 'undefined' && info.process === 'undefined');
  check('Desktop title is Itasha Editor', await application.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].getTitle()) === 'Itasha Editor');
  await page.evaluate(() => localStorage.setItem('su7-studio-settings', JSON.stringify({ layout: 'both', quality: 'medium', autosave: false, live: true })));
  await page.reload(); await page.waitForFunction(() => window.studio);
  await page.click('#home-new'); await page.fill('#new-project-name', 'Electron-Rust验收'); await page.click('#new-project-create');
  console.log('Loading offline 3D model...');
  await page.waitForFunction(() => studio.ready, null, { timeout: 120000 });
  await page.click('#configuration-confirm'); await page.waitForFunction(() => studio.stage === 'edit');
  const viewer = page.frames().find(f => f.url().includes('/configurator/'));
  assert.ok(viewer);
  check('Offline configurator and 3D editor load in Electron', await viewer.evaluate(() => su7Bridge.info.meshes > 0 || Object.keys(window.__su7Scenes || {}).length > 0));
  const src = 'data:image/png;base64,' + fs.readFileSync(path.join(root, 'tools/fixtures/test-artwork.png')).toString('base64');
  await page.evaluate(async src => { studio.setPart('all', 'left', false); await studio.addImage('Electron素材.png', src); }, src);
  const before = await page.evaluate(() => structuredClone(studio.allLayers.find(l => l.id === studio.selected)));
  check('Image import displays the transform handles', await page.locator('#artwork-selection button:visible').count() === 9);
  await page.fill('#prop-w', String(before.w * 1.2)); await page.locator('#prop-w').press('Tab');
  check('Material properties update the selected layer', (await page.evaluate(() => studio.allLayers.find(l => l.id === studio.selected).w)) > before.w);
  await page.click('#undo'); check('Undo restores the previous material size', Math.abs((await page.evaluate(id => studio.allLayers.find(l => l.id === id).w, before.id)) - before.w) < 1e-5);
  await page.click('#redo'); check('Redo reapplies the material size', (await page.evaluate(id => studio.allLayers.find(l => l.id === id).w, before.id)) > before.w);
  await page.evaluate(() => studio.sync());
  const screenshot = await viewer.evaluate(() => su7Bridge.screenshot());
  const image = PNG.sync.read(Buffer.from(screenshot.split(',')[1], 'base64'));
  const colors = new Set(); for (let i = 0; i < image.data.length; i += 128) colors.add(image.data.subarray(i, i + 3).toString('hex'));
  measurements.preview = { width: image.width, height: image.height, colors: colors.size };
  check('3D capture contains a rendered vehicle', image.width > 300 && image.height > 300 && colors.size > 50);
  fs.writeFileSync(path.join(output, '3D预览.png'), Buffer.from(screenshot.split(',')[1], 'base64'));
  const render = await viewer.evaluate(() => su7Bridge.renderOffscreen({ yaw: -45, pitch: 12, width: 1024, height: 768 }));
  const high = PNG.sync.read(Buffer.from(render.split(',')[1], 'base64'));
  check('Offscreen rendering preserves requested dimensions', high.width === 1024 && high.height === 768);
  const saved = await page.evaluate(() => studio.save(true)); measurements.saved = saved;
  const project = JSON.parse(fs.readFileSync(path.join(data, 'projects', saved.file), 'utf8'));
  check('Rust stores full project assets and layer data', Object.keys(project.assets).length > 0 && project.panels.left.layers.length > 0);
  const snapshot = await page.evaluate(async () => { const l=studio.allLayers[0],x=l.x,pending=studio.save(true);l.x+=123;const saved=await pending;l.x=x;return {saved,x}; });
  check('Queued save captures its original revision before later edits', JSON.parse(fs.readFileSync(path.join(data,'projects',snapshot.saved.file),'utf8')).panels.left.layers[0].x === snapshot.x);
  await page.evaluate(async p => { await studio.openProject(p); }, project);
  check('Saved project reopens in Electron', await page.evaluate(() => studio.project.name === 'Electron-Rust验收'));
  await page.click('#settings-open'); await page.waitForSelector('#performance-threads');
  check('Performance controls use the shared Rust API', await page.locator('#performance-status').innerText().then(t => t.includes('GPU')));
  await page.locator('#settings-dialog .close-dialog').click();
  await page.screenshot({ path: path.join(output, '编辑器.png') });
  await page.fill('#project-name', 'Electron关闭自动保存验收'); await page.dispatchEvent('#project-name', 'change');
  measurements.backendPid = JSON.parse(fs.readFileSync(path.join(data, '.itasha-session.json'))).backendPid;
  await application.close(); application = null;
  check('Closing Electron saves the active project', fs.readdirSync(path.join(data, 'projects')).includes('Electron关闭自动保存验收.su7design'));
  const { execFileSync } = require('node:child_process');
  const processRows = JSON.parse(execFileSync('powershell.exe', ['-NoProfile', '-Command', `@(Get-Process -Id ${measurements.backendPid} -ErrorAction SilentlyContinue | Select-Object Id) | ConvertTo-Json -Compress`], { encoding: 'utf8', windowsHide: true }) || '[]');
  check('Rust backend exits with its Electron owner', Array.isArray(processRows) && processRows.length === 0);
  check('No frontend or shader errors', errors.length === 0);
})().catch(async error => {
  errors.push(error.stack); console.error(error);
  if (page && !page.isClosed()) await page.screenshot({ path: path.join(output, 'failure.png') }).catch(() => {});
  process.exitCode = 1;
}).finally(async () => {
  if (application) await application.close().catch(() => {});
  fs.writeFileSync(path.join(output, 'verification.json'), JSON.stringify({ time: new Date().toISOString(), runtime: 'Electron + Rust', checks, errors, measurements, data }, null, 2));
  console.log(`Completed ${checks.length} checks, ${errors.length} errors`);
});
